"""Queries for the csvsql cases. Every case gets its expected output from
SQLite, except command-line cases with a hand-written "expect" (stdout, exit
status). Cases that expect a failure carry a "control" query that must succeed,
so a program that rejects everything scores nothing."""


def q(cat, sql):
    return {"cat": cat, "args": [sql]}


def err(sql, control):
    """A query that must fail. It only counts when the paired control query,
    a related valid query, is also answered correctly."""
    return {"cat": "errors", "args": [sql], "control": [control]}


def cli(args, expect=None, control=None):
    case = {"cat": "cli", "args": args}
    if expect is not None:
        case["expect"] = expect
    if control is not None:
        case["control"] = control
    return case


